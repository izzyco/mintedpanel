import { describe, expect, it } from "vitest";
import { caseActionsMenuItems, changeCaseSopOptions } from "./changeCaseSop";
import type { CaseDetail, SOPTemplate } from "@/types";

const template = (over: Partial<SOPTemplate>) =>
  ({
    orgId: "org-1",
    payerId: "aetna",
    states: ["CO"],
    groupId: null,
    archived: false,
    currentVersion: 1,
    caseType: null,
    ...over,
  }) as SOPTemplate;

const templates = [
  template({ id: "current", name: "Aetna Colorado initial" }),
  template({ id: "alternative", name: "Aetna Colorado alternate", currentVersion: 2 }),
];

const baseCase = {
  id: "case-1",
  payerId: "aetna",
  groupId: "group-1",
  state: "CO",
  caseType: null,
  caseStatus: "not_started",
  provider: { id: "provider-1" },
  tasks: [
    {
      id: "task-1",
      sopTemplateId: "current",
      isAutoGenerated: true,
      status: "not_started",
      completedDate: null,
      sopContent: [{ isCompleted: false }],
    },
  ],
} as unknown as CaseDetail;

describe("changeCaseSopOptions", () => {
  it("is eligible on an untouched case with another matching template", () => {
    const r = changeCaseSopOptions(templates, baseCase, true);
    expect(r.eligible).toBe(true);
    expect(r.currentTemplateId).toBe("current");
    expect(r.alternatives.map((t) => t.id)).toEqual(["alternative"]);
  });

  it("is not eligible once task work begins", () => {
    const c = {
      ...baseCase,
      tasks: [{ ...baseCase.tasks![0], status: "in_progress" }],
    } as CaseDetail;
    expect(changeCaseSopOptions(templates, c, true).eligible).toBe(false);
  });

  it("is not eligible once a step is ticked or carries an attachment", () => {
    const ticked = {
      ...baseCase,
      tasks: [{ ...baseCase.tasks![0], sopContent: [{ isCompleted: true }] }],
    } as unknown as CaseDetail;
    const attached = {
      ...baseCase,
      tasks: [{ ...baseCase.tasks![0], sopContent: [{ isCompleted: false, attachments: [{}] }] }],
    } as unknown as CaseDetail;
    expect(changeCaseSopOptions(templates, ticked, true).eligible).toBe(false);
    expect(changeCaseSopOptions(templates, attached, true).eligible).toBe(false);
  });

  it("is not eligible for a read-only viewer", () => {
    expect(changeCaseSopOptions(templates, baseCase, false).eligible).toBe(false);
  });

  it("is not eligible on a closed case", () => {
    const c = { ...baseCase, caseStatus: "submitted" } as CaseDetail;
    expect(changeCaseSopOptions(templates, c, true).eligible).toBe(false);
  });

  it("is not eligible when the only match is the current template", () => {
    const r = changeCaseSopOptions([templates[0]], baseCase, true);
    expect(r.eligible).toBe(false);
    expect(r.alternatives).toEqual([]);
  });

  it("never offers a legacy SOP to a typed Enrollment case", () => {
    const c = { ...baseCase, caseType: "enrollment" } as CaseDetail;
    expect(changeCaseSopOptions(templates, c, true).eligible).toBe(false);
  });

  it("is never eligible for recredentialing or contract cases", () => {
    for (const caseType of ["recredentialing", "contract"] as const) {
      const typed = templates.map((t) => ({ ...t, caseType }));
      const c = { ...baseCase, caseType } as CaseDetail;
      expect(changeCaseSopOptions(typed, c, true).eligible).toBe(false);
    }
  });

  it("ignores a template authored for a different group", () => {
    const r = changeCaseSopOptions(
      [templates[0], template({ id: "other-group", groupId: "group-2" })],
      baseCase,
      true,
    );
    expect(r.eligible).toBe(false);
  });
});

describe("caseActionsMenuItems", () => {
  it("admin with an eligible swap gets both, delete last", () => {
    expect(caseActionsMenuItems({ changeTemplateEligible: true, isAdmin: true })).toEqual([
      "change_template",
      "delete_case",
    ]);
  });

  it("admin with nothing to swap gets delete only", () => {
    expect(caseActionsMenuItems({ changeTemplateEligible: false, isAdmin: true })).toEqual([
      "delete_case",
    ]);
  });

  it("specialist gets change template only when eligible", () => {
    expect(caseActionsMenuItems({ changeTemplateEligible: true, isAdmin: false })).toEqual([
      "change_template",
    ]);
    expect(caseActionsMenuItems({ changeTemplateEligible: false, isAdmin: false })).toEqual([]);
  });
});
