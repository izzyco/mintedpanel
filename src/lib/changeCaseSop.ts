// Case-page "Change checklist template" eligibility. Pure: the case page's ⋯
// menu asks this whether to offer the item at all. There is deliberately no
// "unavailable" state — when no other matching SOP exists the item is absent,
// because telling a coordinator a feature they did not ask for is unavailable
// is a non-event.
import { isAllStates, templateStates } from "@/lib/sopMatchKey";
import { isFallbackTemplate } from "@/lib/pickTemplate";
import type { CaseDetail, SOPTemplate } from "@/types";

export interface ChangeCaseSopOptions {
  /** True only when the item belongs in the menu: every rule holds AND at
   * least one other matching template exists. */
  eligible: boolean;
  /** Every same-type template that matches this case's payer/state/group,
   * including the current one (the dialog lists it disabled). */
  options: SOPTemplate[];
  /** `options` minus the template the case was generated from. */
  alternatives: SOPTemplate[];
  currentTemplateId: string | null;
}

type ChangeCaseSopCase = Pick<
  CaseDetail,
  "payerId" | "groupId" | "state" | "caseType" | "caseStatus" | "provider" | "tasks"
>;

/** Same-type, non-archived, published templates that match the case key. A
 * generic fallback matches every case of its type. */
export function matchingCaseSopTemplates(
  templates: readonly SOPTemplate[],
  c: ChangeCaseSopCase,
): SOPTemplate[] {
  return templates.filter((t) => {
    if (t.archived || !t.currentVersion || (t.caseType ?? null) !== (c.caseType ?? null))
      return false;
    if (isFallbackTemplate(t)) return true;
    if (t.payerId !== c.payerId) return false;
    if (t.groupId !== null && t.groupId !== c.groupId) return false;
    const states = templateStates(t);
    return isAllStates(states) || states.includes(c.state);
  });
}

/** The checklist is still exactly what generation created: nothing started,
 * no step ticked, no evidence attached. Replacing it loses no work. */
export function isCaseChecklistUntouched(tasks: CaseDetail["tasks"]): boolean {
  return (tasks ?? []).every(
    (t) =>
      t.isAutoGenerated &&
      t.status === "not_started" &&
      !t.completedDate &&
      !t.sopContent?.some((step) => step.isCompleted || (step.attachments?.length ?? 0) > 0),
  );
}

export function changeCaseSopOptions(
  templates: readonly SOPTemplate[],
  c: ChangeCaseSopCase,
  canEdit: boolean,
): ChangeCaseSopOptions {
  const tasks = c.tasks ?? [];
  const currentTemplateId = tasks.find((t) => t.sopTemplateId)?.sopTemplateId ?? null;
  const options = matchingCaseSopTemplates(templates, c);
  const alternatives = options.filter((t) => t.id !== currentTemplateId);
  const ruleHolds =
    canEdit &&
    c.provider != null &&
    (c.caseStatus === "not_started" || c.caseStatus === "in_progress") &&
    c.caseType !== "recredentialing" &&
    c.caseType !== "contract" &&
    isCaseChecklistUntouched(tasks);
  return {
    eligible: ruleHolds && alternatives.length > 0,
    options,
    alternatives,
    currentTemplateId,
  };
}

export type CaseActionsMenuItem = "change_template" | "delete_case";

/** What the case ⋯ menu holds, in order. Delete is admin-only and always
 * last; an empty list means the ⋯ button is not rendered at all (billing, and
 * a specialist with nothing to swap). */
export function caseActionsMenuItems(input: {
  changeTemplateEligible: boolean;
  isAdmin: boolean;
}): CaseActionsMenuItem[] {
  const items: CaseActionsMenuItem[] = [];
  if (input.changeTemplateEligible) items.push("change_template");
  if (input.isAdmin) items.push("delete_case");
  return items;
}
